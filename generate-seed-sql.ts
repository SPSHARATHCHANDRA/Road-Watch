/**
 * Generates supabase/seed.sql from the same sample data used in demo mode.
 * Usage: npm run seed:sql
 * Timestamps are written relative to now(), so the data looks recent whenever the seed is run.
 */
import { writeFileSync } from 'node:fs'
import { INCIDENT_SEEDS, REPORT_SEEDS, SEGMENT_SEEDS, buildSeed } from '../src/data/seed'
import { simulateReadings } from '../src/data/sensorSimulator'

const q = (v: string | number | null | boolean) =>
  v === null ? 'null' : typeof v === 'number' || typeof v === 'boolean' ? String(v) : `'${v.replace(/'/g, "''")}'`
const ago = (hours: number) => `now() - interval '${Math.round(hours * 60)} minutes'`

const now = Date.now()
const { segments, incidents, reports } = buildSeed(now)
const out: string[] = []
out.push('-- ROADWATCH sample data (SIMULATED DEMO DATA). Generated by scripts/generate-seed-sql.ts — do not edit by hand.')
out.push('-- Run AFTER the migration. Re-running replaces the sample rows (ids are fixed).')
out.push('begin;')
out.push(`delete from public.sensor_readings where is_simulated;`)
out.push(`delete from public.incidents where id in (${incidents.map((i) => q(i.id)).join(', ')});`)
out.push(`delete from public.citizen_reports where reference like 'RW-DEMO-%';`)
out.push(`delete from public.road_segments where id in (${segments.map((s) => q(s.id)).join(', ')});`)

out.push('\ninsert into public.road_segments (id, name, area, latitude, longitude, length_km, condition, last_inspected_at) values')
out.push(
  segments
    .map((s, i) => `  (${q(s.id)}, ${q(s.name)}, ${q(s.area)}, ${s.latitude}, ${s.longitude}, ${s.length_km}, ${q(s.condition)}, ${ago(SEGMENT_SEEDS[i][6] * 24)})`)
    .join(',\n') + ';',
)

out.push('\ninsert into public.incidents (id, title, category, description, location, latitude, longitude, severity, status, segment_id, is_simulated, created_at, updated_at) values')
out.push(
  incidents
    .map((inc, i) => {
      const h = INCIDENT_SEEDS[i][4]
      const updatedH = (now - new Date(inc.updated_at).getTime()) / 3600_000
      return `  (${q(inc.id)}, ${q(inc.title)}, ${q(inc.category)}, ${q(inc.description)}, ${q(inc.location)}, ${inc.latitude}, ${inc.longitude}, ${q(inc.severity)}, ${q(inc.status)}, ${q(inc.segment_id)}, true, ${ago(h)}, ${ago(updatedH)})`
    })
    .join(',\n') + ';',
)
out.push(`update public.incident_history h set created_at = i.created_at from public.incidents i where h.incident_id = i.id and i.is_simulated and h.action = 'created';`)

out.push('\ninsert into public.citizen_reports (id, reference, category, location_description, latitude, longitude, severity, description, created_at, updated_at) values')
out.push(
  reports
    .map((r, i) => {
      const h = REPORT_SEEDS[i][6]
      return `  (${q(r.id)}, ${q(r.reference)}, ${q(r.category)}, ${q(r.location_description)}, ${q(r.latitude)}, ${q(r.longitude)}, ${q(r.severity)}, ${q(r.description)}, ${ago(h)}, ${ago(h)})`
    })
    .join(',\n') + ';',
)

const readings = simulateReadings(segments, 48, now)
const currentBucket = Math.floor(now / 3600_000)
out.push('\ninsert into public.sensor_readings (sensor_id, segment_id, metric, value, unit, recorded_at, is_simulated) values')
out.push(
  readings
    .map((r) => {
      const hoursBack = currentBucket - Math.floor(new Date(r.recorded_at).getTime() / 3600_000)
      return `  (${q(r.sensor_id)}, ${q(r.segment_id)}, ${q(r.metric)}, ${r.value}, ${q(r.unit)}, date_trunc('hour', now()) - interval '${hoursBack} hours', true)`
    })
    .join(',\n') + ';',
)
out.push('commit;')

writeFileSync(new URL('../supabase/seed.sql', import.meta.url), out.join('\n') + '\n')
console.log(`Wrote supabase/seed.sql: ${segments.length} segments, ${incidents.length} incidents, ${reports.length} reports, ${readings.length} sensor readings`)
